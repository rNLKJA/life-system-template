#!/usr/bin/env python3
"""vault-link.py: wire the workspace into a connected, readable Obsidian vault.

Deterministic and idempotent: run it after filing, moving or archiving anything. A second
run with nothing new changes nothing.

What it does
  1. Folder notes  every folder (down to a dated group) gets a note named after it
                   (Areas/Finance/Finance.md) whose generated section lists its subfolders,
                   its notes, and its files as plain-text rows plus a live Bases table.
  2. Roles         folder notes in the top HUB_DEPTH levels, and those of folders holding
                   MEMORY.md or PROJECT.md, are `type: hub`; deeper folder notes are
                   `type: index`; notes in a "... Summaries" folder are `type: feed`. A type
                   set by hand (area, project, reference...) is kept.
  3. Up-links      `up: "[[nearest hub]]"` in every writable note, so hiding indexes in the
                   graph strands nothing. A folder index's own up-link follows the folder chain.
  4. Links         relative Markdown links to notes become [[wikilinks]].

The graph filter in .obsidian/graph.json hides index, feed and system notes, so Obsidian's
graph shows hubs and content. Text between the vault-index markers is generated: edit
above or below it, never inside.

Never written: the home README.md (it is also the repository's front page), LOG.md,
CONVERSATION-LOG.md, SKILL.md, AGENTS.md, CLAUDE.md, the template folders, nested code
repositories, and anything in the index-only zones except their index notes. Writing keeps each note's modified time, so activity checks still see real edits.

Usage
    python3 scripts/vault-link.py            # apply
    python3 scripts/vault-link.py --dry-run  # report only
    python3 scripts/vault-link.py --strip    # remove everything this script added
"""
from __future__ import annotations

import argparse
import os
import re
import sys
from collections import defaultdict
from pathlib import Path
from urllib.parse import quote, unquote

sys.path.insert(0, str(Path(__file__).resolve().parent))
import folder_index as FI  # noqa: E402
from workspace import (FEED_SUFFIX, HUB_DEPTH, HUB_MARKERS, INDEX_ONLY, NO_INDEX, NOT_HUBS,  # noqa: E402
                       ROOT, TOP_SKIP)

READONLY_NAMES = {"LOG.md", "CONVERSATION-LOG.md", "SKILL.md", "AGENTS.md", "CLAUDE.md"}
PACKAGE_MARKERS = (".git", "package.json", "pyproject.toml", "Cargo.toml", "go.mod")
SKIP_DIRS = {"node_modules", ".venv", "venv", "__pycache__"}
ROOT_NOTES = {"README.md", "MEMORY.md", "INBOX.md", "ARCHIVE.md", "AGENTS.md", "LOG.md"}
OWN_TYPES = ("", "hub", "index", "feed")  # the types this script writes; any other was set by hand

IDX_START = "<!-- vault-index:start · generated by scripts/vault-link.py, edits here are overwritten -->"
IDX_END = "<!-- vault-index:end -->"
IDX_RE = re.compile(r"\n*" + re.escape(IDX_START[:22]) + r".*?" + re.escape(IDX_END) + r"\n?", re.S)
MDLINK_RE = re.compile(r"(?<!!)\[([^\]\n]*)\]\(\s*(<[^>\n]+>|[^)\s]+)\s*\)")
FENCE_RE = re.compile(r"(```.*?```|~~~.*?~~~|`[^`\n]*`)", re.S)


# ---------------------------------------------------------------- paths

def parent(rel: str) -> str:
    return rel.rsplit("/", 1)[0] if "/" in rel else ""


def under(rel: str, dirs) -> bool:
    return any(rel == d or rel.startswith(d + "/") for d in dirs)


def folder_note(d: str) -> str:
    return f"{d}/{d.rsplit('/', 1)[-1]}.md" if d else "README.md"


def discover():
    """Notes in scope, and the nested code repositories (never written)."""
    notes, pkg_roots = [], set()
    for dp, dn, fn in os.walk(ROOT):
        rd = os.path.relpath(dp, ROOT).replace(os.sep, "/")
        rd = "" if rd == "." else rd
        if rd and any(os.path.exists(os.path.join(dp, m)) for m in PACKAGE_MARKERS):
            pkg_roots.add(rd)
            dn[:] = []
            continue
        dn[:] = sorted(d for d in dn if not d.startswith(".") and d not in SKIP_DIRS
                       and not (not rd and d in TOP_SKIP) and not os.path.islink(os.path.join(dp, d)))
        for f in sorted(fn):
            rel = f"{rd}/{f}" if rd else f
            if f.endswith(".md") and not os.path.islink(os.path.join(dp, f)) and (rd or f in ROOT_NOTES):
                notes.append(rel)
    return notes, pkg_roots


# ---------------------------------------------------------------- links and frontmatter

def wikilink(rel: str, label: str | None = None) -> str:
    if re.search(r"[\[\]#^|]", rel):
        return f"[{label or rel}]({quote(rel, safe='/()')})"
    t = rel[:-3] if rel.endswith(".md") else rel
    return f"[[{t}|{label}]]" if label and label != t.rsplit("/", 1)[-1] else f"[[{t}]]"


def split_fm(text: str):
    """(frontmatter lines or None, body); False when the frontmatter cannot be parsed safely."""
    if not text.startswith("---\n"):
        return None, text
    end = text.find("\n---", 4)
    if end < 0 or end > 6000:
        return False, text
    close = text.find("\n", end + 1)
    close = len(text) if close < 0 else close + 1
    lines = text[4:end].split("\n") if end > 4 else []
    if any(l and not (re.match(r"^[A-Za-z0-9_\-]+:", l) or l.startswith((" ", "-", "\t", "#"))) for l in lines):
        return False, text
    return lines, text[close:]


def get_field(text: str, key: str) -> str:
    fm, _ = split_fm(text)
    for l in fm or []:
        if l.startswith(f"{key}:"):
            return l.split(":", 1)[1].strip().strip('"').strip("'")
    return ""


def set_field(text: str, key: str, value: str | None) -> str | None:
    """Set (or with None remove) one frontmatter key, keeping every other line as written."""
    fm, body = split_fm(text)
    if fm is False:
        return None
    fm = list(fm or [])
    idx = [i for i, l in enumerate(fm) if l.startswith(f"{key}:")]
    if value:
        if idx:
            fm[idx[0]] = f"{key}: {value}"
            fm = [l for i, l in enumerate(fm) if i not in idx[1:]]
        else:
            fm.append(f"{key}: {value}")
    else:
        fm = [l for i, l in enumerate(fm) if i not in idx]
    if not fm:
        return body.lstrip("\n") if text.startswith("---\n") else body
    return "---\n" + "\n".join(fm) + "\n---\n" + body


def convert_links(text: str, rel: str, note_set) -> tuple[str, int]:
    """Relative Markdown links to notes in the vault become wikilinks (code is left alone)."""
    n, base = 0, parent(rel)

    def repl(m):
        nonlocal n
        label, raw = m.group(1), m.group(2).strip("<>")
        if re.match(r"^[a-z]+:", raw, re.I) or raw.startswith("#"):
            return m.group(0)
        path, _, anchor = unquote(raw).partition("#")
        tgt = os.path.normpath(os.path.join(base, path)).replace(os.sep, "/")
        if not path.endswith(".md") or tgt not in note_set or re.search(r"[\[\]#^|]", tgt):
            return m.group(0)
        n += 1
        t = tgt[:-3] + (f"#{anchor}" if anchor else "")
        pipe = "\\|" if m.string[m.string.rfind("\n", 0, m.start()) + 1:m.start()].lstrip().startswith("|") else "|"
        return f"[[{t}{pipe}{label}]]" if label and label != t else f"[[{t}]]"

    parts = FENCE_RE.split(text)
    for i in range(0, len(parts), 2):
        parts[i] = MDLINK_RE.sub(repl, parts[i])
    return "".join(parts), n


# ---------------------------------------------------------------- structure

def build(notes, pkg_roots, inv):
    """Folder notes (hubs and indexes), who lists whom, and every note's up-link."""
    note_set = set(notes)
    hubs = {"": "README.md"}
    for d in sorted(set(FI.index_dirs(inv)) | {parent(n) for n in notes if n == folder_note(parent(n))}):
        if d and not under(d, pkg_roots) and not under(d, NO_INDEX):
            hubs[d] = FI.folder_note_name(d, inv) if d in inv else folder_note(d)
    created = [h for h in hubs.values() if h not in note_set]
    hub_files = set(hubs.values())

    def hand_type(rel: str) -> str:
        p = ROOT / rel
        return get_field(p.read_text(encoding="utf-8", errors="replace")[:6000], "type") if p.exists() else ""

    def is_hub_dir(d: str) -> bool:
        if not d or d.count("/") + 1 <= HUB_DEPTH:
            return True
        if under(d, NOT_HUBS):
            return False
        return any((ROOT / d / m).exists() for m in HUB_MARKERS) or hand_type(hubs[d]) in ("area", "project")

    hub_dirs = {d for d in hubs if is_hub_dir(d)}

    def nearest(d: str, among) -> str:
        while d not in among:
            d = parent(d)
        return d

    owner, children, up_of = {}, defaultdict(set), {}
    for n in notes + created:
        if n == "README.md" or under(n, NO_INDEX):
            continue  # templates are scaffolding: never listed or linked, so they stay out of the graph
        d = parent(n)
        is_folder_note = n in hub_files and hubs.get(d) == n
        lister = hubs[nearest(parent(d) if is_folder_note else d, hubs)]
        owner[n] = lister
        children[lister].add(n)
        if is_folder_note and d not in hub_dirs:
            up_of[n] = lister  # an index keeps its folder chain
        else:
            up_of[n] = hubs[nearest(parent(d) if is_folder_note else d, hub_dirs)]
    return hubs, created, children, up_of, hub_dirs


def index_block(hub: str, kids, hub_files, parts) -> str:
    head, folders, files = parts if parts else ([], [], [])
    sub_hubs = sorted(k for k in kids if k in hub_files)
    notes = sorted(k for k in kids if k not in hub_files)
    out = [IDX_START, "", "## In this folder", ""] + head + folders
    if sub_hubs and not parts:
        out += [f"- {wikilink(h, parent(h).rsplit('/', 1)[-1] or 'Home')}" for h in sub_hubs] + [""]
    if notes:
        out += (["**Notes**", ""] if parts else []) + [f"- {wikilink(n)}" for n in notes] + [""]
    out += files + [IDX_END]
    return "\n".join(out)


# ---------------------------------------------------------------- main

def main() -> int:
    ap = argparse.ArgumentParser(description="Wire the vault: folder notes, roles, up-links, indexes.")
    ap.add_argument("--dry-run", action="store_true", help="report only")
    ap.add_argument("--strip", action="store_true", help="remove everything this script added")
    a = ap.parse_args()

    notes, pkg_roots = discover()
    inv = FI.inventory(ROOT)
    hubs, created, children, up_of, hub_dirs = build(notes, pkg_roots, inv)
    hub_files = set(hubs.values())
    hub_dir = {h: d for d, h in hubs.items()}
    note_set = set(notes) | set(created)
    frozen = set(NO_INDEX) | pkg_roots
    stats, skipped = defaultdict(int), []
    # notes first, then folder notes, so each index sees its folder's final state
    order = [n for n in sorted(note_set) if n not in hub_files] + [h for h in sorted(note_set) if h in hub_files]
    stat_cache = private = None
    for rel in order:
        name = rel.rsplit("/", 1)[-1]
        is_hub = rel in hub_files
        if rel == "README.md":
            continue  # the home note doubles as the repository's front page: it stays as written
        if name in READONLY_NAMES or under(rel, frozen) or (under(rel, INDEX_ONLY) and not is_hub):
            stats["read_only"] += 1
            continue
        if is_hub and stat_cache is None:
            inv = FI.inventory(ROOT) if not (a.dry_run or a.strip) else inv
            stat_cache = FI.subtree_stats(inv)
            paths = [f"{d}/{f}" if d else f for d in inv for f, _, _ in inv[d]["files"]] + list(hub_dir.values())
            private = FI.private_set(ROOT, paths)
        path = ROOT / rel
        orig = path.read_text(encoding="utf-8", errors="replace") if path.exists() else f"# {hub_dir[rel].rsplit('/', 1)[-1]}\n"
        orig = orig[1:] if orig.startswith("﻿") else orig
        text = IDX_RE.sub("\n", orig).rstrip("\n") + "\n"
        if a.strip:
            text = set_field(text, "up", None)
            if text is not None:
                text = set_field(text, "updated", None)
            if text is not None and get_field(text, "type") in ("hub", "index", "feed"):
                text = set_field(text, "type", None)
        else:
            up = up_of.get(rel)
            text = set_field(text, "up", f'"{wikilink(up, "Home" if up == "README.md" else None)}"' if up else None)
            if text is not None:
                text, n = convert_links(text, rel, note_set)
                stats["links_converted"] += n
            if text is not None and is_hub:
                d = hub_dir[rel]
                parts = None
                if d and d in inv:
                    parts = FI.render(d, inv, stat_cache, private, private is not None and rel in private,
                                      wikilink, lambda cd: hubs.get(cd), under(d, INDEX_ONLY))
                    newest = stat_cache[d][1]
                    text = set_field(text, "updated", FI.day(newest) if newest else None) or text
                    if get_field(text, "type") in OWN_TYPES:
                        want = "hub" if d in hub_dirs else "index"
                        if get_field(text, "type") != want:
                            text = set_field(text, "type", want) or text
                    stats["indexes"] += 1
                text = text.rstrip("\n") + "\n\n" + index_block(rel, children.get(rel, []), hub_files, parts) + "\n"
            elif text is not None and parent(rel).endswith(FEED_SUFFIX) and get_field(text, "type") in ("", "feed"):
                text = set_field(text, "type", "feed") or text
        if text is None:
            skipped.append(rel)
            continue
        if text != orig or not path.exists():
            stats["created" if not path.exists() else "updated"] += 1
            if not a.dry_run:
                path.parent.mkdir(parents=True, exist_ok=True)
                st = path.stat() if path.exists() else None
                path.write_text(text, encoding="utf-8")
                if st:  # generated metadata is not an edit: keep the modified time activity checks read
                    os.utime(path, (st.st_atime, st.st_mtime))
    print(f"notes in scope: {len(notes)} | folder notes: {len(hubs)} ({len(hub_dirs)} hubs, "
          f"{len(hubs) - len(hub_dirs)} indexes, new: {len(created)}) | code repositories left alone: {len(pkg_roots)}")
    for k in sorted(stats):
        print(f"  {k}: {stats[k]}")
    if skipped:
        print("  skipped (frontmatter could not be parsed safely):", *skipped, sep="\n    ")
    if a.dry_run:
        print("dry run: nothing written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
